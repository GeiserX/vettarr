"""Turn today's environment variables into an equivalent config.yaml.

Values that are secrets are never written: the file gets ``${VAR}`` and the
environment keeps the value. Only what lives in the environment is imported;
word lists, post formats and link shapes that today sit in code are not, and
the file says so where they would go.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from urllib.parse import urlsplit

from ruamel.yaml.comments import CommentedMap, CommentedSeq

from vettarr.config.loader import dump, parse, plain
from vettarr.config.schema import QBIT_DEFAULT_ACCOUNT
from vettarr.config.signals import MEDIA_TYPES

# Variables whose values are secrets, or private enough to keep out of a file.
SECRET_VARS = frozenset({
    "TELEGRAM_API_ID",
    "TELEGRAM_API_HASH",
    "TELEGRAM_PHONE",
    "TELEGRAM_BOT_TOKEN",
    "TMDB_API_KEY",
    "PROWLARR_API_KEY",
    "QBITTORRENT_PASS",
    "GOOGLE_BOOKS_API_KEY",
})
_TRACKER_SECRET = re.compile(r"^TRACKER_\d+_PASSWORD$")
_TRUE = {"1", "true", "yes", "on"}


def is_secret(name: str) -> bool:
    return name in SECRET_VARS or bool(_TRACKER_SECRET.match(name))


def secret_names(env: Mapping[str, str]) -> list[str]:
    """The secret variables set in ``env``: what must never appear in the output."""
    return sorted(name for name, value in env.items() if value and is_secret(name))


def render(env: Mapping[str, str], example_text: str) -> str:
    return dump(build(env, example_text))


def document(env: Mapping[str, str]) -> CommentedMap:
    """The config document ``env`` stands for, built on the shipped example.

    The one mapping from environment variables to config: ``config import-env``
    writes it to a file, and the app boots from it in memory when there is no
    config file.
    """
    from vettarr.config.cli import example_text

    return build(env, example_text())


def build(env: Mapping[str, str], example_text: str) -> CommentedMap:
    example = parse(example_text, "config.example.yaml")

    def has(name: str) -> bool:
        return bool(env.get(name, "").strip())

    def ref(name: str) -> str:
        return "${" + name + "}"

    def url(name: str) -> str:
        # A URL carrying a password, a query or a fragment may hold a token,
        # so it stays in the environment too.
        value = env[name].strip()
        parts = urlsplit(value)
        return ref(name) if parts.password or parts.query or parts.fragment else value

    def number(name: str, default: str | None = None) -> int:
        raw = env.get(name, "").strip() or default
        try:
            return int(raw)  # type: ignore[arg-type]
        except (TypeError, ValueError):
            raise ValueError(f"{name} is not a whole number") from None

    doc = CommentedMap()
    doc.yaml_set_start_comment(
        "Generated by `config import-env` from the environment variables.\n"
        "Secrets stay in the environment as ${VAR}. POSTGRES_*, LOG_LEVEL and TZ\n"
        "remain environment variables and are not part of this file."
    )

    # --- telegram ---
    telegram = CommentedMap()
    for key, name in (("api_id", "TELEGRAM_API_ID"), ("api_hash", "TELEGRAM_API_HASH"), ("phone", "TELEGRAM_PHONE")):
        if has(name):
            telegram[key] = ref(name)
    # The session file an existing deployment already has: its name predates
    # the rename, and a new name would ask for a fresh Telegram login.
    telegram["session_path"] = (env.get("SESSION_DIR", "").strip() or "/data/sessions").rstrip("/") + "/media_triage"
    if has("TELEGRAM_BOT_TOKEN"):
        telegram["bot_token"] = ref("TELEGRAM_BOT_TOKEN")
    if has("TELEGRAM_OWNER_ID"):
        telegram["reviewers"] = _flow([number("TELEGRAM_OWNER_ID")])
    doc["telegram"] = telegram

    # --- sources ---
    sources = CommentedSeq()
    if has("TELEGRAM_GROUP_ID"):
        source = CommentedMap()
        source["key"] = "group"
        source["kind"] = "userbot"
        source["chat"] = number("TELEGRAM_GROUP_ID")
        source["backfill"] = "since_last"
        source["on_download"] = "delete"
        source["on_reject"] = "delete"
        sources.append(source)
    doc["sources"] = sources

    # --- formats ---
    formats = _fresh([f for f in example.get("formats", []) if f.get("kind") == "scene"])
    doc["formats"] = formats
    doc.yaml_set_comment_before_after_key(
        "formats",
        before="Your group's card format is not in the environment. Add a card profile\n"
        "here (see config.example.yaml); a source with no `formats` uses every profile.",
    )

    # --- providers ---
    providers = CommentedSeq()
    used: set[str] = set()
    for n in range(1, 100):
        prefix = f"TRACKER_{n}_"
        if not has(prefix + "URL"):
            break
        name = env.get(prefix + "NAME", "").strip() or f"tracker-{n}"
        key = _unique(_slug(name) or f"tracker-{n}", used)
        provider = CommentedMap()
        provider["key"] = key
        provider["base_url"] = url(prefix + "URL")
        auth = CommentedMap()
        if has(prefix + "USERNAME") and has(prefix + "PASSWORD"):
            auth["from"] = "login"
            auth["username"] = env[prefix + "USERNAME"].strip()
            auth["password"] = ref(prefix + "PASSWORD")
            if has(prefix + "COOKIE_PATH"):
                auth["cookie_file"] = env[prefix + "COOKIE_PATH"].strip()
        elif has(prefix + "COOKIE_PATH"):
            auth["from"] = "cookie_file"
            auth["cookie_file"] = env[prefix + "COOKIE_PATH"].strip()
        else:
            auth["from"] = "prowlarr"
        provider["auth"] = auth
        if has(prefix + "LOGGED_OUT_MARKER"):
            provider["logged_out_marker"] = env[prefix + "LOGGED_OUT_MARKER"]
        if auth["from"] != "prowlarr":
            provider["search"] = "unit3d"
        # Both are opt-in, and the environment has no variable that opts in.
        # They are written off, with UNIT3D's values ready to turn on.
        thank = CommentedMap()
        thank["enabled"] = False
        thank["path"] = "/torrents/{id}"
        thank["method"] = "LIVEWIRE"
        provider["thank"] = thank
        keep_alive = CommentedMap()
        keep_alive["enabled"] = False
        keep_alive["every_minutes"] = 360
        keep_alive["path"] = "/torrents"
        provider["keep_alive"] = keep_alive
        providers.append(provider)
    doc["providers"] = providers
    if providers:
        doc.yaml_set_comment_before_after_key(
            "providers",
            before="Tracker links are not in the environment: add `links` per provider\n"
            "(see config.example.yaml). Thank and keep-alive are off: they act on your\n"
            "account, and some trackers forbid automation. Set `enabled: true` on the\n"
            "ones you want.",
        )

    # --- integrations ---
    integrations = CommentedMap()
    if has("PROWLARR_URL"):
        block = CommentedMap()
        block["url"] = url("PROWLARR_URL")
        if has("PROWLARR_API_KEY"):
            block["api_key"] = ref("PROWLARR_API_KEY")
        integrations["prowlarr"] = block
    if has("QBITTORRENT_URL"):
        block = CommentedMap()
        block["url"] = url("QBITTORRENT_URL")
        # The default only when unset: a variable set to empty meant an empty name.
        block["username"] = env.get("QBITTORRENT_USER", QBIT_DEFAULT_ACCOUNT).strip()
        if has("QBITTORRENT_PASS"):
            block["password"] = ref("QBITTORRENT_PASS")
        integrations["qbittorrent"] = block
        integrations.yaml_set_comment_before_after_key(
            "qbittorrent",
            before="Categories and save paths are in code today, not in the environment:\n"
            "add `categories` and `save_paths` per media type.",
            indent=2,
        )
    if has("TMDB_API_KEY"):
        block = CommentedMap()
        block["api_key"] = ref("TMDB_API_KEY")
        # Titles and genre names come back in this language. 0.11 had no
        # setting for it and always asked in es-ES, so that is what is written.
        block["language"] = "es-ES"
        integrations["tmdb"] = block
    integrations["imdb_guide"] = CommentedMap(enabled=True)
    if has("GOOGLE_BOOKS_API_KEY"):
        block = CommentedMap()
        block["api_key"] = ref("GOOGLE_BOOKS_API_KEY")
        integrations["google_books"] = block
    doc["integrations"] = integrations

    # --- deliver ---
    deliver = CommentedMap()
    if has("QBITTORRENT_URL"):
        for media_type in MEDIA_TYPES:
            deliver[media_type] = "qbittorrent"
    doc["deliver"] = deliver

    # --- policy ---
    policy = CommentedMap()
    enabled = env.get("AUTO_APPROVE_ENABLED", "").strip().lower() in _TRUE
    policy["auto_approve"] = "on" if enabled else "off"
    policy["min_votes"] = number("MIN_GUIDE_VOTES", "5")
    # The default only when unset: AUTO_APPROVE_TYPES= (empty) approves no type.
    allowed = {
        part.strip().lower()
        for part in env.get("AUTO_APPROVE_TYPES", "movie,series,magazine").split(",")
        if part.strip()
    }
    wait = number("AUTO_APPROVE_MAX_WAIT_HOURS", "24")
    types = CommentedMap()
    for media_type in MEDIA_TYPES:
        entry = CommentedMap()
        if media_type not in allowed or media_type == "music":
            entry["mode"] = "never"
        elif media_type == "magazine":
            entry["mode"] = "always"
        else:
            entry["mode"] = "rules"
            entry["when_data_missing"] = "wait"
            entry["max_wait_hours"] = wait
        types[media_type] = entry
    policy["types"] = types
    policy["lists"] = CommentedMap()
    policy.yaml_set_comment_before_after_key(
        "lists",
        before="Keyword, genre and subject lists are never in the environment, and the\n"
        "rules below are the public defaults: add your lists here and a rule for\n"
        "each (matches_any). A type in mode `rules` that no rule applies to is\n"
        "held for a person.",
        indent=2,
    )
    policy["rules"] = _fresh(example["policy"]["rules"])
    doc["policy"] = policy

    # --- release words ---
    doc["release_words"] = _fresh(example["release_words"])
    doc.yaml_set_comment_before_after_key(
        "release_words",
        before="The words your group's posts use for a language, subtitles or a whole\n"
        "season are not in the environment. These are the English defaults: add\n"
        "your group's words to each list, or the signals that read them see none.",
    )

    web = CommentedMap()
    web["bind"] = "0.0.0.0"
    web["port"] = number("WEB_PORT", "4850")
    doc["web"] = web
    return doc


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:64]


def _unique(key: str, used: set[str]) -> str:
    candidate, n = key, 2
    while candidate in used:
        candidate = f"{key}-{n}"
        n += 1
    used.add(candidate)
    return candidate


def _fresh(node: object) -> object:
    """A copy of part of the example without its comments, which belong to the example."""
    data = plain(node)

    def build(value: object) -> object:
        if isinstance(value, dict):
            return CommentedMap((k, build(v)) for k, v in value.items())
        if isinstance(value, list):
            items = [build(v) for v in value]
            if all(not isinstance(v, (dict, list)) for v in items):
                return _flow(items)
            return CommentedSeq(items)
        return value

    return build(data)


def _flow(items: list[object]) -> CommentedSeq:
    seq = CommentedSeq(items)
    seq.fa.set_flow_style()
    return seq
